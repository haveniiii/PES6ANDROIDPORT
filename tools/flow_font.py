#!/usr/bin/env python3
"""The Flow touch controls' lettering: a signed distance field of a real typeface, so the labels
stay sharp at any size (docs/37 §9).
  python3 tools/flow_font.py <BarlowCondensed-SemiBold.ttf> runtime/android/flow_font.h
Barlow Condensed is by Jeremy Tribby, under the SIL Open Font License 1.1; only the capitals,
digits and '+' go in, as a generated field, and the font file stays out of the repo."""
import sys
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from scipy.ndimage import distance_transform_edt as edt

CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789+"
COLS, CELL_W, CELL_H = 8, 48, 60     # the atlas
SCALE = 6                            # rendered this much larger, then reduced
SPREAD = 5.0                         # the field reaches this far, in atlas pixels
font = ImageFont.truetype(sys.argv[1], 44 * SCALE)
rows = (len(CHARS) + COLS - 1) // COLS
W, H = COLS * CELL_W, rows * CELL_H
atlas = np.zeros((H, W), np.uint8)
ascent, _ = font.getmetrics()
cap_h = -font.getbbox("H", anchor="ls")[1]
metrics = []
for i, ch in enumerate(CHARS):
    im = Image.new("L", (CELL_W * SCALE, CELL_H * SCALE), 0)
    base = (CELL_H * SCALE + cap_h) // 2
    x0 = (CELL_W * SCALE - font.getlength(ch)) / 2
    ImageDraw.Draw(im).text((x0, base), ch, 255, font=font, anchor="ls")
    a = np.asarray(im) > 127
    d = (edt(a) - edt(~a)) / SCALE                       # + inside, in atlas pixels
    d = d[SCALE // 2 :: SCALE, SCALE // 2 :: SCALE][:CELL_H, :CELL_W]
    x, y = (i % COLS) * CELL_W, (i // COLS) * CELL_H
    atlas[y : y + CELL_H, x : x + CELL_W] = np.clip(d / SPREAD * 127.5 + 127.5, 0, 255).astype(np.uint8)
    metrics.append(font.getlength(ch) / cap_h)            # advance, in cap heights
cap_px = cap_h / SCALE
with open(sys.argv[2], "w") as f:
    f.write("/* Generated by tools/flow_font.py: Barlow Condensed SemiBold as a distance field.\n"
            " * Copyright 2017 The Barlow Project Authors (https://github.com/jpt/barlow), SIL Open Font\n"
            " * License 1.1: runtime/android/flow_font.OFL.txt */\n")
    f.write(f'#define FLOW_FONT_W {W}\n#define FLOW_FONT_H {H}\n#define FLOW_FONT_COLS {COLS}\n')
    f.write(f'#define FLOW_FONT_CELL_W {CELL_W}\n#define FLOW_FONT_CELL_H {CELL_H}\n#define FLOW_FONT_CAP {cap_px:.3f}f\n')
    f.write(f'static const char FLOW_FONT_CHARS[] = "{CHARS}";\n')
    f.write("static const float FLOW_FONT_ADVANCE[] = {" + ",".join(f"{m:.4f}f" for m in metrics) + "};\n")
    f.write("static const unsigned char FLOW_FONT_PX[] = {\n")
    b = atlas.tobytes()
    for k in range(0, len(b), 32):
        f.write(",".join(map(str, b[k : k + 32])) + ",\n")
    f.write("};\n")
Image.fromarray(atlas).save(sys.argv[2] + ".png") if len(sys.argv) > 3 else None
print(W, H, "cap", cap_px)
