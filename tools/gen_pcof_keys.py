#!/usr/bin/env python3
"""Write runtime/common/pcof_keys.h from tools/data/pes6_pc_of_keys.json (docs/38 §8): the PES6 PC
option file's key tables for the app's own converter (runtime/common/pcof.c).

    python3 tools/gen_pcof_keys.py
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
k = json.load(open(os.path.join(ROOT, "tools/data/pes6_pc_of_keys.json")))
out = ["/* PES6PORT — the PES6 PC option file's key tables (docs/28, docs/38 §8). GENERATED by",
       " * tools/gen_pcof_keys.py from tools/data/pes6_pc_of_keys.json (as published by the community's",
       " * editors: PESEditor, COFPES-OF-Editor-6); do not edit. */",
       "#ifndef PES6_PCOF_KEYS_H", "#define PES6_PCOF_KEYS_H", "", "#include <stdint.h>", "",
       "#define PCOF_BLOCKS %d" % len(k["block"]), "#define PCOF_KEY_WORDS %d" % len(k["key"]), "",
       "static const uint32_t PCOF_BLOCK[PCOF_BLOCKS] = { %s };" % ", ".join(map(str, k["block"])),
       "static const uint32_t PCOF_BLOCK_SIZE[PCOF_BLOCKS] = { %s };" % ", ".join(map(str, k["block_size"])),
       "static const uint8_t PCOF_KEY_PC[256] = {"]
kp = k["key_pc"]
for i in range(0, 256, 16):
    out.append("    " + ", ".join("0x%02X" % x for x in kp[i:i + 16]) + ",")
out.append("};")
out.append("static const uint32_t PCOF_KEY[PCOF_KEY_WORDS] = {")
kk = k["key"]
for i in range(0, len(kk), 6):
    out.append("    " + ", ".join("0x%08X" % x for x in kk[i:i + 6]) + ",")
out += ["};", "", "#endif", ""]
open(os.path.join(ROOT, "runtime/common/pcof_keys.h"), "w").write("\n".join(out))
