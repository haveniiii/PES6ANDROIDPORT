#!/usr/bin/env python3
"""Sort the phrases of a PES6 PS2 voice bank into commentary events (docs/24).

    python3 tools/commentary/classify.py build/comm/wav OUT_DIR

Input: the transcriptions whisper.cpp left next to each clip (<clip>.wav.txt, Spanish).
Output in OUT_DIR:
  commentary.txt   the catalogue runtime/common/commentary.c reads ("event clip clip ...")
  phrases.tsv      clip, seconds, event (or "-"), transcription: to review and correct by hand
  overrides.txt    (optional input, kept) "clip event" lines that win over the rules; "clip -" drops
A phrase gets an event when exactly one rule matches it (the rules are ordered so that the more
specific win: "palo" before "remate"). Phrases with a score in words ("dos a uno") also get
score_<a>_<b>, and the director only says those when the score is right.
"""
import os
import re
import struct
import sys
import wave

RULES = [   # (event, regex on the lower-cased transcription); first match wins
    ('woodwork',   r'\b(palo|travesa|horizontal|poste|vertical)'),
    ('offside',    r'(fuera de juego|off ?side|posici[oó]n adelantada|adelantado)'),
    ('goal',       r'\b(go+l+|golazo|adentro|a la red|la mand[oó] a guardar|anot[oó]|convierte|marc[oó])'),
    ('save',       r'(atajad|ataja|tapad|tap[oó]|manos del (arquero|portero)|salv[oó]|desv[ií]a el arquero|detiene|atrapa)'),
    ('shot',       r'(remat|dispar|tir[oa] al arco|le peg[oó]|al arco|por (arriba|encima)|desviad|afuera|cerca del palo|chut)'),
    ('header',     r'(de cabeza|cabezazo|cabece)'),
    ('foul',       r'(falta|infracci|foul|amarilla|roja|amonest|expuls|tiro libre)'),
    ('corner',     r'(c[oó]rner|tiro de esquina|saque de esquina)'),
    ('goal_kick',  r'(saque de (arco|meta|puerta)|saque del arquero)'),
    ('throw_in',   r'(lateral|saque de banda|saque lateral)'),
    ('kickoff',    r'(comienza|empieza|arranca|pitazo inicial|pone en marcha|rueda la pelota|saque inicial|se inicia)'),
    ('half_time',  r'(primer tiempo|medio tiempo|descanso|entretiempo)'),
    ('full_time',  r'(final del partido|termin[oó]|pitazo final|se acab[oó]|fin del partido)'),
    ('through_pass', r'(profundidad|al vac[ií]o|habilit|en largo)'),
    ('lofted_pass',  r'(centro|centra|pase largo|cambio de frente|globo)'),
]
NUM = {'cero': 0, 'uno': 1, 'una': 1, 'dos': 2, 'tres': 3, 'cuatro': 4, 'cinco': 5, 'seis': 6}
SCORE = re.compile(r'\b(cero|uno|una|dos|tres|cuatro|cinco|seis|\d) (?:a|por) (cero|uno|una|dos|tres|cuatro|cinco|seis|\d)\b')
NOISE = re.compile(r'^\s*(\[[^\]]*\]|\([^)]*\)|\*[^*]*\*|\.+|subt[ií]tulos.*)\s*$', re.I)


def seconds(path):
    try:
        with wave.open(path) as w:
            return w.getnframes() / w.getframerate()
    except Exception:
        return 0.0


def main():
    src, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    over = {}
    op = os.path.join(out, 'overrides.txt')
    if os.path.exists(op):
        for line in open(op):
            q = line.split('#', 1)[0].split()
            if len(q) >= 2:
                over[int(q[0])] = q[1]
    cat, rows = {}, []
    for name in sorted(os.listdir(src)):
        if not name.endswith('.wav.txt'):
            continue
        clip = int(name[:5])
        text = ' '.join(open(os.path.join(src, name), errors='replace').read().split())
        low = text.lower()
        ev = '-'
        if text and not NOISE.match(text):
            for e, rx in RULES:
                if re.search(rx, low):
                    ev = e
                    break
        m = SCORE.search(low)
        score = None
        if m:
            a, b = (NUM.get(x, int(x) if x.isdigit() else -1) for x in m.groups())
            if a >= 0 and b >= 0:
                score = 'score_%d_%d' % (max(a, b), min(a, b))
        ev = over.get(clip, ev)
        secs = seconds(os.path.join(src, name[:-4]))
        rows.append((clip, secs, ev, score or '', text))
        if ev != '-' and secs <= 8.0:           # long clips are intros and summaries
            cat.setdefault(ev, []).append(clip)
        if score and secs <= 8.0:
            cat.setdefault(score, []).append(clip)
    with open(os.path.join(out, 'phrases.tsv'), 'w') as fh:
        fh.write('clip\tseconds\tevent\tscore\ttext\n')
        for r in rows:
            fh.write('%d\t%.2f\t%s\t%s\t%s\n' % r)
    with open(os.path.join(out, 'commentary.txt'), 'w') as fh:
        fh.write('# Generated by tools/commentary/classify.py from whisper transcriptions (docs/24).\n')
        for e in sorted(cat):
            fh.write('%s %s\n' % (e, ' '.join(str(c) for c in cat[e])))
    print('%d phrases, %d classified' % (len(rows), sum(1 for r in rows if r[2] != '-')))
    for e in sorted(cat, key=lambda k: -len(cat[k])):
        print('  %-14s %d' % (e, len(cat[e])))


if __name__ == '__main__':
    main()
