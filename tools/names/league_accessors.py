#!/usr/bin/env python3
"""Name the accessors of the league data block (docs/23) after the part they touch.

    python3 tools/names/league_accessors.py      # -> tools/names/league.txt

Functions of any program whose decompiled C (build/decomp) reads `_DAT_08c16080 + OFF` for a
single OFF, and that have no name of their own (or only an ownership name), become
league_<OFF>_<address>: "reads or writes the sub-block at root + OFF". league.txt sits between
scenes.txt and events.txt in tools/names/build_names.py.
"""
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
WEAK = re.compile(r'^(FUN_|thunk_FUN_|.*_(part|only)_[0-9A-F]{8}$)')


def main():
    out = ['# Generated by tools/names/league_accessors.py: league_<offset>_<address> touches',
           '# the league data block *0x08C16080 + offset (docs/23).']
    for path in sorted(glob.glob(os.path.join(ROOT, 'build/decomp/*/*.c'))):
        prog = os.path.basename(os.path.dirname(path))
        base = os.path.basename(path)[:-2]
        addr, name = base[:8], base[9:]
        if not WEAK.match(name):
            continue
        offs = set(re.findall(r'_DAT_08c16080 \+ 0x([0-9a-f]+)', open(path).read()))
        if len(offs) != 1:
            continue
        pre = '' if prog == 'eboot' else prog + '.ovl:'
        out.append('%s%s league_%05X_%s' % (pre, addr, int(offs.pop(), 16), addr))
    with open(os.path.join(ROOT, 'tools/names/league.txt'), 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    print('%d league accessors -> tools/names/league.txt' % (len(out) - 2))


if __name__ == '__main__':
    main()
