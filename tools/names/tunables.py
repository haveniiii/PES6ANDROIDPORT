#!/usr/bin/env python3
"""runtime/common/pes6_tuning.h -> build/names/tunables_<program>.txt (ALLEGREX_TUNABLES), and
runtime/common/pes6_hooks.h -> build/names/hooks_<program>.txt (ALLEGREX_HOOKS, docs/25 §3).

    python3 tools/names/tunables.py

Each PES6_TUNE_CODE line gives a parameter name, its program, the original register value and
the instruction addresses; the recompiler, given "<address> <name> <original bits>" lines,
emits `rt = psp_tune_<name>;` at those instructions and stops if one of them does not hold
the original value (docs/25 §2). Also checks that a float's original matches its bits.
"""
import os
import re
import struct

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    src = open(os.path.join(ROOT, 'runtime/common/pes6_tuning.h')).read()
    per_prog = {}
    for m in re.finditer(r'^PES6_TUNE_CODE\((.*)\)\s*$', src, re.M):
        args = [a.strip() for a in re.split(r',(?=(?:[^"]*"[^"]*")*[^"]*$)', m.group(1))]
        name, typ, prog, orig, bits, _what = args[:6]
        bits = int(bits.rstrip('uU'), 16)
        if typ == 'PES6_T_F32' and struct.unpack('<I', struct.pack('<f', float(orig)))[0] != bits:
            raise SystemExit('%s: %s is not 0x%08X as a float' % (name, orig, bits))
        if typ == 'PES6_T_INT' and int(orig, 0) & 0xFFFFFFFF != bits:
            raise SystemExit('%s: %s is not 0x%08X' % (name, orig, bits))
        tag = 'eboot' if prog.strip('"') == 'EBOOT.elf' else prog.strip('"')[:-4]
        for a in args[6:]:
            per_prog.setdefault(tag, []).append((int(a.rstrip('uU'), 16), name, bits))
    os.makedirs(os.path.join(ROOT, 'build/names'), exist_ok=True)
    for old in os.listdir(os.path.join(ROOT, 'build/names')):
        if old.startswith('tunables_') and old.endswith('.txt'):
            os.unlink(os.path.join(ROOT, 'build/names', old))
    hooks = {}
    for m in re.finditer(r'^PES6_HOOK\((\w+),\s*"([^"]+)",\s*(0x[0-9A-Fa-f]+)u?,', open(
            os.path.join(ROOT, 'runtime/common/pes6_hooks.h')).read(), re.M):
        tag = 'eboot' if m.group(2) == 'EBOOT.elf' else m.group(2)[:-4]
        hooks.setdefault(tag, []).append((int(m.group(3), 16), m.group(1)))
    for old in os.listdir(os.path.join(ROOT, 'build/names')):
        if old.startswith('hooks_') and old.endswith('.txt'):
            os.unlink(os.path.join(ROOT, 'build/names', old))
    for tag, rows in sorted(hooks.items()):
        with open(os.path.join(ROOT, 'build/names', 'hooks_%s.txt' % tag), 'w') as f:
            f.write('# Generated by tools/names/tunables.py from runtime/common/pes6_hooks.h\n')
            for a, n in sorted(rows):
                f.write('%08X %s\n' % (a, n))
        print('hooks: %s %d function(s) -> build/names/hooks_%s.txt' % (tag, len(rows), tag))
    for tag, rows in sorted(per_prog.items()):
        with open(os.path.join(ROOT, 'build/names', 'tunables_%s.txt' % tag), 'w') as f:
            f.write('# Generated by tools/names/tunables.py from runtime/common/pes6_tuning.h\n')
            for a, n, b in sorted(rows):
                f.write('%08X %s %08X\n' % (a, n, b))
        print('tunables: %s %d instruction(s) -> build/names/tunables_%s.txt' % (tag, len(rows), tag))


if __name__ == '__main__':
    main()
