#!/usr/bin/env python3
"""Merge the known names of the game's functions into one file per program for
the recompiler (ALLEGREX_NAMES, docs/20 §3 and §5).

    python3 tools/names/build_names.py [--auto]

Sources, later ones winning on the same address:
  build/pes6.sym             PPSSPP's symbol export: the SDK it recognises (EBOOT only)
  build/ghidra_symbols.txt   Ghidra's names that are not FUN_xxx / thunk_FUN_xxx (EBOOT only)
  tools/names/imports.txt    stub_<firmware function>: the EBOOT's import stubs (import_names.py)
  tools/names/auto/<p>.txt   names proven from firmware/task evidence (tools/ghidra/AutoName.py)
  tools/names/parts.txt      OWNER_part_<addr>: helpers only reachable from one named function
                             (tools/names/derive_parts.py; regenerate after adding names)
  tools/names/scenes.txt     <scene>_only_<addr>: EBOOT functions seen running in one scene only
                             (tools/names/scene_only.py over tools/tour.sh profiles)
  tools/names/league.txt     league_<off>_<addr>: accessors of the league data block (league_accessors.py)
  tools/names/events.txt     functions tied to one match event by a run-time profile
                             (tools/names/fnprof_events.py --emit), same syntax as curated.txt
  tools/names/curated.txt    the game's own functions, named by hand as they are understood;
                             "game.ovl:08D4E880 name" names a function of an overlay
--auto first refreshes tools/names/auto/ from build/names/auto_<program>.tsv.
Outputs (versioned: names, not code): tools/names/pes6_eboot.txt and
tools/names/ovl/<overlay>.txt, which tools/ovl_recomp.py passes to the emitter.
"""
import argparse
import collections
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
NAMES = os.path.join(ROOT, 'tools/names')
EBOOT = 'EBOOT.elf'
# when one address gets several automatic names, the strongest evidence wins
# layers that say whose code a function is: they only fill functions with no other name
OWNERSHIP = ('parts', 'scenes', 'league')
RULES = ['task', 'thread', 'callback', 'intr', 'alarm', 'wrapper']


def ident(name):
    name = re.sub(r'[^A-Za-z0-9_]', '_', name)
    return name if not name[:1].isdigit() else '_' + name


def refresh_auto():
    """build/names/auto_<program>.tsv -> tools/names/auto/<program>.txt"""
    os.makedirs(os.path.join(NAMES, 'auto'), exist_ok=True)
    for tsv in sorted(glob.glob(os.path.join(ROOT, 'build/names/auto_*.tsv'))):
        prog = os.path.basename(tsv)[5:-4]
        prog = EBOOT if prog == 'eboot' else prog
        props = collections.defaultdict(list)          # addr -> [(rule, name, evidence)]
        for line in open(tsv, errors='replace'):
            p = line.rstrip('\n').split('\t')
            if len(p) >= 4 and p[2] in RULES:
                props[int(p[0], 16)].append((p[2], p[1], p[3]))
        chosen = {}
        for addr, cands in props.items():
            best = min(RULES.index(r) for r, _, _ in cands)
            cands = [c for c in cands if RULES.index(c[0]) == best]
            tasks = sorted({n.rsplit('_', 1)[0] for r, n, _ in cands if r == 'task'})
            if len(tasks) == 1:     # one task function used for several roles: init_main
                roles = [n.rsplit('_', 1)[1] for r, n, _ in cands]
                roles = [x for x in ('init', 'main', 'exit') if x in roles]
                chosen[addr] = (tasks[0] + '_' + '_'.join(roles), cands[0][0], cands[0][2])
            else:
                chosen[addr] = (cands[0][1], cands[0][0], cands[0][2])
        seen = collections.Counter()
        out = os.path.join(NAMES, 'auto', ('eboot' if prog == EBOOT else prog[:-4]) + '.txt')
        with open(out, 'w') as f:
            f.write('# Generated by tools/names/build_names.py --auto from tools/ghidra/AutoName.py.\n')
            f.write('# <address> <name>  # rule: evidence\n')
            for addr in sorted(chosen):
                name, rule, ev = chosen[addr]
                seen[name] += 1
                if seen[name] > 1:          # the same task/thread created in two places
                    name = '%s_%d' % (name, seen[name])
                f.write('%08X %s  # %s: %s\n' % (addr, ident(name), rule, ev))
        print('auto: %d names -> %s' % (len(chosen), os.path.relpath(out, ROOT)))


def read_pairs(path):
    for line in open(path, errors='replace'):
        line = line.split('#', 1)[0].split()
        if len(line) >= 2:
            yield line[0], line[1]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--auto', action='store_true', help='refresh tools/names/auto/ first')
    a = ap.parse_args()
    if a.auto:
        refresh_auto()

    names = collections.defaultdict(dict)     # program -> addr -> name
    origin = collections.defaultdict(dict)

    def put(prog, addr, name, src):
        names[prog][addr] = ident(name)
        origin[prog][addr] = src

    sym = os.path.join(ROOT, 'build/pes6.sym')
    if os.path.exists(sym):
        for line in open(sym, errors='replace'):
            m = re.match(r'([0-9A-Fa-f]{8}) ([^,\s]+)', line)
            if m and not m.group(2).startswith('z_un_'):
                put(EBOOT, int(m.group(1), 16), m.group(2), 'ppsspp')
    gh = os.path.join(ROOT, 'build/ghidra_symbols.txt')
    if os.path.exists(gh):
        for line in open(gh, errors='replace'):
            parts = line.split()
            if len(parts) >= 2 and not re.match(r'(thunk_)?FUN_', parts[1]):
                put(EBOOT, int(parts[0], 16), parts[1], 'ghidra')
    imports = os.path.join(NAMES, 'imports.txt')          # import_names.py: firmware stubs
    if os.path.exists(imports):
        for addr, name in read_pairs(imports):
            put(EBOOT, int(addr, 16), name, 'imports')
    for path in sorted(glob.glob(os.path.join(NAMES, 'auto', '*.txt'))):
        base = os.path.basename(path)[:-4]
        prog = EBOOT if base == 'eboot' else base + '.ovl'
        for addr, name in read_pairs(path):
            put(prog, int(addr, 16), name, 'auto')
    for src in ('parts', 'scenes', 'league', 'events', 'curated'):   # derive_parts, scene_only, league_accessors, fnprof_events
        path = os.path.join(NAMES, src + '.txt')
        if not os.path.exists(path):
            continue
        for addr, name in read_pairs(path):
            prog, _, addr = addr.rpartition(':')
            prog, addr = prog or EBOOT, int(addr, 16)
            if src in OWNERSHIP and addr in names[prog]:
                continue        # whose code, not what it does: never over a name that says what
            put(prog, addr, name, src)

    os.makedirs(os.path.join(NAMES, 'ovl'), exist_ok=True)
    for prog in sorted(names):
        out = os.path.join(NAMES, 'pes6_eboot.txt' if prog == EBOOT else
                           os.path.join('ovl', prog.replace('.ovl', '.txt')))
        with open(out, 'w') as f:
            f.write('# Generated by tools/names/build_names.py -- edit tools/names/curated.txt instead.\n')
            f.write('# <address> <name> (source)\n')
            for addr in sorted(names[prog]):
                f.write(f'{addr:08X} {names[prog][addr]}  # {origin[prog][addr]}\n')
        counts = collections.Counter(origin[prog].values())
        print(f'{prog}: {len(names[prog])} names -> {os.path.relpath(out, ROOT)}  ({dict(counts)})')


if __name__ == '__main__':
    main()
