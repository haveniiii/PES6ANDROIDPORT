#!/usr/bin/env python3
"""Name the EBOOT's firmware import stubs after the function they import.

    python3 tools/names/import_names.py      # -> tools/names/imports.txt

Each stub (8 bytes in the import table, 0x08998xxx) becomes psp_import_<addr> in the emitted
build/gen/pes6_imports.c, which calls psp_hle_call(<NID>). The NID is looked up in PPSSPP's
database (tools/ghidra/ppsspp_niddb.xml); the stub is named stub_<firmware name>. Without
this, the ownership layers called them <caller>_part_<addr>. build_names.py reads the file
right above Ghidra's names.
"""
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def main():
    nids = dict(re.findall(r'<NID>0x([0-9A-Fa-f]{8})</NID><NAME>([^<]+)</NAME>',
                           open(os.path.join(ROOT, 'tools/ghidra/ppsspp_niddb.xml')).read()))
    nids = {k.upper(): v for k, v in nids.items()}
    src = open(os.path.join(ROOT, 'build/gen/pes6_imports.c')).read()
    stubs = re.findall(r'psp_import_([0-9A-F]{8})\(void\) \{[^}]*psp_hle_call\(0x([0-9A-F]{8})u\)', src)
    out = os.path.join(ROOT, 'tools/names/imports.txt')
    known = 0
    with open(out, 'w') as f:
        f.write('# Generated by tools/names/import_names.py: firmware import stubs of the EBOOT.\n')
        f.write('# <stub address> stub_<firmware function>  # NID\n')
        for addr, nid in sorted(stubs):
            name = nids.get(nid)
            known += name is not None
            f.write('%s stub_%s  # %s\n' % (addr, name or 'nid_' + nid, nid))
    print('imports: %d stubs, %d with a known name -> %s' % (len(stubs), known, os.path.relpath(out, ROOT)))


if __name__ == '__main__':
    main()
