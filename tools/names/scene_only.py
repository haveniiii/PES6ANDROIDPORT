#!/usr/bin/env python3
"""Name functions that only ever run in one scene (docs/20 §6).

    python3 tools/names/scene_only.py build/tour/f*.tsv [--min-runs 1]   # -> tools/names/scenes.txt

Input: PES6_FNPROF profiles with the scene-mask column (tools/tour.sh in the trace build),
ideally covering every scene. A function whose scene mask, OR-ed over all the profiles, has
a single bit gets <scene>_only_<address>. Overlay functions count only from profiles that
record the program of each address (several overlays share addresses). scenes.txt sits
between parts.txt and events.txt in tools/names/build_names.py.
"""
import argparse
import collections
import glob
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fnprof_lib  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCENES = {0: 'boot', 1: 'bootcheck', 2: 'intro', 3: 'title', 4: 'menu', 5: 'loading', 6: 'edit',
          7: 'masterleague', 8: 'match', 12: 'demo', 13: 'scene13', 14: 'training', 15: 'wireless'}


def load_names():
    """(program, address) -> name, skipping ownership names (parts and scene names)."""
    names = {}
    paths = [('EBOOT.elf', os.path.join(ROOT, 'tools/names/pes6_eboot.txt'))]
    paths += [(os.path.basename(f)[:-4] + '.ovl', f)
              for f in glob.glob(os.path.join(ROOT, 'tools/names/ovl/*.txt'))]
    for prog, path in paths:
        for line in open(path):
            q = line.split('#', 1)[0].split()
            if len(q) >= 2 and not re.search(r'_(part|only)_[0-9A-F]{8}$', q[1]):
                names[(prog, int(q[0], 16))] = q[1]
    return names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('profiles', nargs='+')
    args = ap.parse_args()
    mask = collections.defaultdict(int)
    for path in args.profiles:
        with_prog = fnprof_lib.has_program_column(path)
        for prog, func, _n, m, _frames in fnprof_lib.read(path):
            if m is not None and (prog == fnprof_lib.EBOOT or with_prog):
                mask[(prog, func)] |= m
    names = load_names()
    out = ['# Generated by tools/names/scene_only.py: functions seen running in one scene only',
           '# (union of the PES6_FNPROF scene masks of: %s).' % ' '.join(os.path.basename(p) for p in args.profiles)]
    count = collections.Counter()
    for (prog, addr) in sorted(mask):
        m = mask[(prog, addr)]
        if (prog, addr) in names or m == 0 or m & (m - 1):
            continue
        scene = SCENES.get(m.bit_length() - 1, 'scene%d' % (m.bit_length() - 1))
        pre = '' if prog == fnprof_lib.EBOOT else prog + ':'
        out.append('%s%08X %s_only_%08X' % (pre, addr, scene, addr))
        count[(prog, scene)] += 1
    with open(os.path.join(ROOT, 'tools/names/scenes.txt'), 'w') as fh:
        fh.write('\n'.join(out) + '\n')
    print('%d functions seen; one scene only: %d' % (len(mask), sum(count.values())))
    for (prog, scene), n in sorted(count.items(), key=lambda x: -x[1])[:25]:
        print('  %-22s %-14s %d' % (prog, scene, n))


if __name__ == '__main__':
    main()
