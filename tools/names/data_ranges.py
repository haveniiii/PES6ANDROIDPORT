#!/usr/bin/env python3
"""tools/names/data.txt -> build/names/data_ranges.txt, the recompiler's ALLEGREX_DATA_NAMES.

    python3 tools/names/data_ranges.py

Each global of data.txt becomes a range "<address> <size> <label>", and every named field of
a struct (pes6_types.h) inside it one more: charas[3].state, ball_ptr, sheets[12].attr+0x4.
The field offsets are not re-typed here: they come from the compiler itself
(clang -Xclang -fdump-record-layouts on runtime/common/pes6_types.h), so the labels can never
disagree with the structs. The emitter prints the innermost label containing the address of a
load or store whose base register holds a known constant (docs/20 §8).
"""
import os
import re
import subprocess
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SCALAR = {'char': 1, 'uint8_t': 1, 'int8_t': 1, 'uint16_t': 2, 'int16_t': 2, 'uint32_t': 4, 'int32_t': 4, 'float': 4}


def layouts():
    """{struct: (size, [(offset, size, field)])} from clang's record layout dump."""
    with tempfile.NamedTemporaryFile('w', suffix='.c', delete=False) as t:
        t.write('#include "pes6_types.h"\n')
        names = re.findall(r'typedef struct (pes6_\w+)', open(os.path.join(ROOT, 'runtime/common/pes6_types.h')).read())
        for n in names:
            t.write('%s _use_%s;\n' % (n, n))          # force a layout for each
    out = subprocess.run(['clang', '-std=c11', '-fsyntax-only', '-Xclang', '-fdump-record-layouts',
                          '-I', os.path.join(ROOT, 'runtime/common'), t.name],
                         capture_output=True, text=True, check=True).stdout
    os.unlink(t.name)
    res, cur = {}, None
    for line in out.splitlines():
        m = re.match(r'\s*0 \| struct (pes6_\w+)$', line)
        if m:
            cur = m.group(1)
            res[cur] = [0, []]
            continue
        m = re.match(r'\s*(\d+) \|\s{3}(\S.*\S) (\w+)$', line)      # top-level fields only (3 spaces)
        if cur and m and not m.group(3).startswith('_unk'):
            res[cur][1].append((int(m.group(1)), m.group(2), m.group(3)))
        m = re.match(r'\s*\| \[sizeof=(\d+),', line)
        if cur and m:
            res[cur][0] = int(m.group(1))
            cur = None
    return res


def sizeof(t, lay):
    t = t.strip()
    n = 1
    m = re.match(r'(.*)\[(\d+)\]$', t)
    if m:
        t, n = m.group(1).strip(), int(m.group(2))
    if t.endswith('*'):
        return 4 * n
    t = t.replace('struct ', '')
    return (SCALAR.get(t) or lay[t][0]) * n


def main():
    lay = layouts()
    rows = []
    for line in open(os.path.join(ROOT, 'tools/names/data.txt')):
        p = line.split('#', 1)[0].split()
        if len(p) < 3:
            continue
        addr, name, typ = int(p[0], 16), p[1], p[2]
        base = typ.split('[')[0]
        count = int(typ.split('[')[1].rstrip(']')) if '[' in typ else 1
        if base.endswith('*') or base not in lay:
            rows.append((addr, sizeof(typ, lay), name))
            continue
        size, fields = lay[base]
        rows.append((addr, size * count, name))
        for i in range(count):
            elem = '%s[%d]' % (name, i) if '[' in typ else name
            for off, ftype, fname in fields:
                rows.append((addr + i * size + off, sizeof(ftype, lay), '%s.%s' % (elem, fname)))
    rows.sort()
    out = os.path.join(ROOT, 'build/names/data_ranges.txt')
    with open(out, 'w') as f:
        f.write('# Generated by tools/names/data_ranges.py from tools/names/data.txt: <address> <size> <label>\n')
        for a, s, n in rows:
            f.write('%08X %X %s\n' % (a, s, n))
    print('data ranges: %d (%d globals) -> %s' % (len(rows), sum(1 for _ in open(os.path.join(ROOT, 'tools/names/data.txt'))
                                                                if _.strip() and not _.startswith('#')), os.path.relpath(out, ROOT)))


if __name__ == '__main__':
    main()
